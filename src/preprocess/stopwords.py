def load_stopwords(extra: Iterable[str] | None = None) -> set[str]:
    """Return default domain stopwords merged with optional extra stopword terms."""
    stopwords = set(DEFAULT_STOPWORDS)
    if extra is not None:
        for term in extra:
            cleaned = str(term).strip()
            if cleaned:
                stopwords.add(cleaned)
    return stopwords
